import { describe, expect, it } from 'vitest';
import { summarize } from './summary';

/**
 * Опис у видачі Google — часто єдине, що людина читає до кліку. Обірване
 * посеред слова речення виглядає як помилка сайту, тому межі перевіряємо.
 */
describe('опис для видачі', () => {
	it('короткий текст лишається як є', () => {
		expect(summarize('Сатинова сукня.', 100)).toBe('Сатинова сукня.');
	});

	it('зайві пробіли й переноси зводяться до одного', () => {
		expect(summarize('Сатин\n\nз блиском', 100)).toBe('Сатин з блиском');
	});

	it('ріже по межі речення, а не посеред слова', () => {
		const text = 'Класична сукня-міді з віскози. Тримає форму й не мнеться в дорозі.';
		expect(summarize(text, 40)).toBe('Класична сукня-міді з віскози.');
	});

	it('без речення поруч ріже по слову й ставить трикрапку', () => {
		const text = 'Класична сукня-міді з віскози з приталеним ліфом і вільною спідницею';
		const result = summarize(text, 40);

		expect(result.endsWith('…')).toBe(true);
		expect(result.length).toBeLessThanOrEqual(41);
		// Головне: останнє слово ціле.
		expect(text.startsWith(result.slice(0, -1))).toBe(true);
	});

	it('не лишає розділовий знак перед трикрапкою', () => {
		expect(summarize('Сукня з віскози, приталена модель', 20)).toBe('Сукня з віскози…');
	});
});
