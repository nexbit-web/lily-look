/**
 * Які кадри показувати для обраного кольору.
 *
 * Правило одне на весь сайт — і для галереї на сторінці товару, і для
 * обкладинки картки в списках. Саме тому воно живе окремим модулем:
 * коли воно було в двох місцях, місця розійшлись, і на картці стояла
 * чорна куртка, а за кліком відкривалась біла.
 *
 * `color = null` у кадру означає «спільний»: крій, тканина зблизька,
 * бирка — такі кадри доречні за будь-якого вибору.
 */
export function framesForColor<T extends { color: string | null }>(
	images: T[],
	color: string | null
): T[] {
	if (!color) return images;

	const own = images.filter((image) => image.color === color);
	// У кольору немає жодного свого кадру — краще показати всі фото
	// товару, ніж порожнє місце. Так само поводяться старі картки,
	// де колір у фото ще не проставлений.
	if (own.length === 0) return images;

	return images.filter((image) => image.color === color || image.color === null);
}
